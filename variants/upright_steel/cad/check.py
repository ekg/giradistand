"""
CAD validation checks: interference, equipment fit, hole alignment, clearances,
crate removal path, and enclosed envelopes.
Results -> out/cad_checks.md
"""

import itertools
import json
import os
import cadquery as cq

import params as P
import model as M

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "out")
TOL = 1e-3     # mm^3 - ignore numerical noise


def vol_inter(a, b):
    try:
        i = a.intersect(b)
        return 0.0 if i is None else i.Volume()
    except Exception:
        return -1.0


def flat_face_top(tray_solid):
    """Area of horizontal faces on the top surface (should be flat under feet)."""
    z = tray_solid.BoundingBox().zmax
    return [f for f in tray_solid.Faces()
            if f.geomType() == "PLANE" and abs(f.Center().z - z) < 1e-6]


def main():
    parts = M.build()
    lines = ["# CAD validation checks (automatic)", "",
             "Generated by `cad/check.py` from the parametric model, revision R0.9.",
             "All values in mm; volume in mm^3.", ""]
    ok = True

    # 1. pairwise interference of manufactured parts
    man = [(pid, i, s) for pid in ("P1", "P2", "P3", "P4")
           for i, s in enumerate(parts[pid]["solids"])]
    lines += ["## 1. Interference between manufactured parts", "",
              "| A | B | intersection volume | result |", "|---|---|---|---|"]
    for (pa, ia, sa), (pb, ib, sb) in itertools.combinations(man, 2):
        v = vol_inter(sa, sb)
        res = "PASS" if abs(v) <= TOL else "FAIL"
        if res == "FAIL":
            ok = False
        lines.append(f"| {pa}#{ia+1} | {pb}#{ib+1} | {v:.3f} | {res} |")

    # 2. manufactured parts vs equipment envelopes
    eq = {
        "turntable": M.make_tt(), "speakers": M.make_speaker(1).fuse(M.make_speaker(-1)),
        "crate": M.make_crate(), "pads": M.make_pads(1).fuse(M.make_pads(-1)),
        "dust_cover_open": M.make_dust_cover(),
    }
    lines += ["", "## 2. Equipment / storage envelopes vs structure", "",
              "| equipment | part | intersection volume | result |", "|---|---|---|---|"]
    for name, e in eq.items():
        for (pid, i) in [("P1", 0), ("P2", 0), ("P2", 1), ("P3", 0), ("P4", 0)]:
            v = vol_inter(parts[pid]["solids"][i], e)
            res = "PASS" if abs(v) <= TOL else "CHECK"
            if res != "PASS" and name != "dust_cover_open":
                ok = False
            lines.append(f"| {name} | {pid}#{i+1} | {v:.3f} | {res} |")

    # 3. bolt envelopes: every bolt must pass cleanly through every part AND
    #    clear every equipment envelope. A bolt that intersects a plate means
    #    the hole is misaligned; this is the real alignment check.
    lines += ["", "## 3. Fastener envelopes (this doubles as the hole-alignment check)", "",
              "| item | max intersection with P1..P4 (mm3) | max intersection with "
              "equipment (mm3) | result |", "|---|---|---|---|"]
    struct = [parts[pid]["solids"][i] for pid in ("P1", "P2", "P3", "P4")
              for i in range(len(parts[pid]["solids"]))]
    eq_shapes = [M.make_tt(), M.make_speaker(1), M.make_speaker(-1),
                 M.make_crate(), M.make_pads(1), M.make_pads(-1)]
    worst_s = worst_e = 0.0
    n_bolts = 0
    for sgn in (1, -1):
        for (y, z, xf) in M.side_slab_holes():
            b = M.make_bolt(sgn, y, z, xf)
            n_bolts += 1
            for sp in struct:
                worst_s = max(worst_s, abs(vol_inter(b, sp)))
            for e in eq_shapes:
                worst_e = max(worst_e, abs(vol_inter(b, e)))
    ok3 = (worst_s <= TOL and worst_e <= TOL)
    lines.append(f"| all {n_bolts} bolts | {worst_s:.3f} | {worst_e:.3f} | "
                 f"{'PASS' if ok3 else 'FAIL'} |")
    if not ok3:
        ok = False
    # 3b. fastener count and strap
    lines += ["", f"* bolt count in the model: {n_bolts} (22 tray/rear-panel + 1 strap = 23 in",
              "  the BOM; the strap bolt is not modelled because P5 is a loose part).",
              f"* P5 strap hole in the top tray: 6.6 dia at y = {P.STRAP_HOLE['y']:.0f}, "
              f"x = {P.STRAP_HOLE['x']:.0f} (turntable rear face is at y = "
              f"{-P.TT['D']/2:.0f}) -> "
              f"{'clear of the turntable' if P.STRAP_HOLE['y'] < -P.TT['D']/2 else 'CLASH'}"]
    if P.STRAP_HOLE["y"] >= -P.TT["D"] / 2:
        ok = False

    # 4. clearances summary
    c = P.chains()
    lines += ["", "## 5. Fit clearances", "",
              "| check | available | required | margin | result |", "|---|---|---|---|---|"]
    checks = [
        ("speaker pair in bay (width)", c["spk_bay_clear_w"], c["spk_pair"],
         c["spk_pair"]),
        ("crate width in bay", c["tray_w"], P.CRATE["W"], P.CRATE["W"]),
        ("crate depth in bay", c["rec_bay_clear_d"], P.CRATE["D"], P.CRATE["D"]),
        ("crate height in bay", c["h_rec_clear"], P.CRATE["H"], P.CRATE["H"]),
        ("crate top vs mid tray front flange", c["flange_under_mid"], c["crate_top"],
         c["crate_top"]),
        ("speaker top vs top tray underside",
         P.Z_TOP - P.T, P.Z_MID + P.PAD["h"] + P.SPK["H"], P.SPK["H"]),
        ("turntable depth on top tray", P.D_OVER, P.TT["D"], P.TT["D"]),
        ("turntable width on top tray", P.TRAY_W, P.TT["W"], P.TT["W"]),
    ]
    for (name, avail, req, req2) in checks:
        margin = avail - req
        res = "PASS" if margin > 0 else ("TIGHT" if margin > -100 else "FAIL")
        lines.append(f"| {name} | {avail:.1f} | {req:.1f} | {margin:.1f} | {res} |")
        if res == "FAIL":
            ok = False

    # 6. crate removal path
    lines += ["", "## 6. Crate removal path (translation +Y, no rotation)", "",
              "| crate displacement (mm) | interference with frame |", "|---|---|"]
    mid = parts["P2"]["solids"][1]
    bot = parts["P3"]["solids"][0]
    frame = (parts["P1"]["solids"][0].fuse(parts["P1"]["solids"][1])
             .fuse(mid).fuse(bot).fuse(parts["P4"]["solids"][0])).clean()
    for dy in (0, 50, 100, 150, 200, 250, 300, 350, 400):
        cr = M.make_crate().translate(cq.Vector(0, dy, 0))
        v = vol_inter(cr, frame)
        lines.append(f"| {dy} | {v:.3f} |")
        if v > TOL:
            ok = False

    # 7. top surface flatness under turntable feet
    tray_top = parts["P2"]["solids"][0]
    feet = M.make_tt_feet()
    v = vol_inter(tray_top, feet)
    lines += ["", "## 7. Turntable feet support", "",
              f"* TT foot pads vs top tray intersection: {v:.3f} mm^3 "
              f"({'PASS - feet stand on the flat tray surface' if abs(v) < TOL else 'FAIL'})",
              f"* TT foot centre inboard of tray edge: "
              f"{(P.TRAY_W/2) - (P.TT['W']/2 - P.TT['foot_inset_x']):.1f} mm (side), "
              f"{(P.D_OVER/2) - (P.TT['D']/2 - P.TT['foot_inset_y']):.1f} mm (front/rear)",
              f"* flat field inboard of the 3.3 mm bend tangent zone: "
              f"{P.TRAY_W/2 - 3.3:.1f} mm half-width -> "
              f"{'feet clear' if (P.TT['W']/2 - P.TT['foot_inset_x'] + P.TT['foot_dia']/2) < (P.TRAY_W/2 - 3.3) else 'CHECK'}"]

    # 8. dust cover / wall clearance
    dc = M.make_dust_cover()
    bb = dc.BoundingBox()
    lines += ["", "## 8. Dust-cover and wall clearance", "",
              f"* open cover envelope: y from {bb.ymin:.1f} to {bb.ymax:.1f} mm, "
              f"z to {bb.zmax:.1f} mm",
              f"* cover projects {(bb.ymin + P.D_OVER/2):.0f} mm behind the stand rear face "
              f"-> wall clearance for hinged operation: {abs(bb.ymin - (-P.D_OVER/2)):.0f} mm",
              "* with the cover removed for play (A-T recommendation) cable-only clearance "
              "of 80 mm is adequate"]

    lines += ["", f"## Overall result: {'ALL CHECKS PASS' if ok else 'CHECK ITEMS FLAGGED'}"]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "cad_checks.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:8]))
    print("...")
    print(lines[-1])


if __name__ == "__main__":
    main()
