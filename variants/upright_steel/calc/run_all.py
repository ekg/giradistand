"""
Run every calculation and assemble out/calc_report.md.
Usage:  .venv/bin/python calc/run_all.py
"""

import os, sys, json, datetime
_here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _here)
sys.path.insert(0, os.path.join(os.path.dirname(_here), "cad"))
ROOT = os.path.dirname(_here)

import params as P
import shelf, joints, racking, stability, tolerances
from materials import STEEL

HEAD = """# GI-RAD STAND - engineering calculations

VARIANT A (upright speakers): reproducible calculation report, revision **U0.9 (provisional)**.
Generated by `calc/run_all.py` on {date}.

Everything below is computed from `cad/params.py` and the CAD model, so a
parameter change regenerates every number.

## 0. Basis of design

| item | value | source |
|---|---|---|
| material | {mat} | SendCutSend material catalogue |
| E | {E:.0f} MPa | conservative floor for cold-rolled sheet (200-210 GPa textbook) |
| nu | {nu:.2f} | steel |
| G | {G:.0f} MPa | E / 2(1+nu) |
| fy (0.2% proof) | {fy:.0f} MPa | CRS 1008/1010, ASTM A1008 CS Type B |
| fu | {fu:.0f} MPa | CRS typical |
| sheet thickness | {t:.2f} mm | 0.074 in nominal stock |
| design factor vs yield | 2.0 | brief's initial static objective |

**Load cases** (assumptions, not certified ratings):

| shelf | payload | derivation |
|---|---|---|
| top | 15 kg | 8 kg turntable + 7 kg margin / accessory allowance |
| middle | 10 kg | 2 x 3.5 kg speakers + 3.0 kg margin |
| bottom | 40 kg | 22 kg loaded crate (80-100 LPs) + 18 kg margin |
| self weight | {sw:.1f} kg | computed from the CAD volumes |

**Acceptance criteria** (set before the results were computed):

| id | criterion |
|---|---|
| S1 | unrestrained tip force >= 60 N at 900 mm in every stationary configuration |
| S2 | sliding force >= 2 x 60 N |
| D1 | top tray deflection <= 1.5 mm for 15 kg |
| D2 | middle tray deflection <= 1.5 mm, base tray <= 2.5 mm |
| D3 | differential deflection between turntable feet <= 0.5 mm |
| D4 | twist of the turntable support <= 1.0 mm corner to corner |
| R1 | side-to-side racking drift <= 2.0 mm at 100 N |
| R2 | front-to-back drift <= 2.0 mm at 100 N |
| T1 | panel stress <= fy/2 for every load case |
| J1 | clamped joint slip margin >= 5 at 100 N |
| J2 | no force-fitting: worst-case joint misalignment <= available slot movement |
"""


def main():
    sw = sum(s.Volume() for pid, p in __import__("model").build().items()
             if pid in ("P1", "P2", "P3", "P4") for s in p["solids"]) * STEEL["rho"]
    out = [HEAD.format(date=datetime.date.today().isoformat(),
                       mat=STEEL["name"], E=STEEL["E"], G=STEEL["G"],
                       nu=STEEL["nu"], fy=STEEL["fy"], fu=STEEL["fu"],
                       t=STEEL["t"], sw=sw)]
    shelf_txt, _ = shelf.main()
    out += ["## 1-5. Notation and method notes", "",
            "* Sign convention: deflections are reported positive downwards.",
            "* Shelf model: grillage FE (`calc/grillage.py`), plate bending + twisting",
            "  with folded edge beams; validated in 6.1 against two closed-form plate",
            "  solutions. The model is 8-15 % flexible relative to the closed forms, i.e.",
            "  conservative; no calibration factor is applied.",
            "* Joint model (`calc/joints.py`): clamped friction-grip joint with bolt",
            "  bearing as backstop. Capacities are EC3-style design values",
            "  (0.6/0.9 fu As / 1.25), i.e. *not* ultimate and not a certified rating.",
            "* Racking (`calc/racking.py`): three independent mechanisms, each with its",
            "  own stiffness; the friction-dependent one is also evaluated in the",
            "  'friction lost' state to show why it is required.",
            "* Stability (`calc/stability.py`): masses and centres of mass computed from",
            "  the CAD solids; tipping about the real support polygon.",
            ""]
    out += [shelf_txt]
    out += [joints.main()]
    out += [racking.main()]
    stab_txt, rows, props = stability.main()
    out += [stab_txt]
    out += [tolerances.main()]
    out += ["", "## 10. What this report does not establish", "",
            "* No physical test of any kind has been performed. All values are",
            "  analytical (with a self-written FE implementation) plus CAD checks.",
            "* No supplier has reviewed the files, quoted, or accepted them.",
            "* The plywood/steel properties are handbook values, not mill certificates.",
            "* Dynamic behaviour (resonances above ~30 Hz), acoustic isolation and",
            "  long-term creep of the isolation pads are not analysed; they are handled",
            "  by design measures and by the staged home test plan.",
            "* Buckling of the 1.88 mm plates is not governing at the stress levels",
            "  computed (max 47 MPa, t/b ratio 1.88/400); a formal plate buckling check",
            "  would be required for loads several times the design values.",
            ""]
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    with open(os.path.join(ROOT, "out", "calc_report.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote out/calc_report.md", len("\n".join(out)), "chars")


if __name__ == "__main__":
    main()
